import path from "node:path";
import { fileURLToPath } from "node:url";
import { drizzle, type NodePgDatabase } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import pg from "pg";
import * as schema from "./schema";

export * from "./schema";
export { schema };

export type DpDb = NodePgDatabase<typeof schema>;

export function createDb(connectionString: string, options: { max?: number } = {}): { db: DpDb; pool: pg.Pool } {
  const pool = new pg.Pool({
    connectionString,
    max: options.max ?? 10,
    // Managed Postgres providers (Render, Neon, Replit) require TLS; local dev does not.
    ssl: /sslmode=require/.test(connectionString) ? { rejectUnauthorized: false } : undefined,
  });
  return { db: drizzle(pool, { schema }), pool };
}

/** Default location of the SQL migrations generated by drizzle-kit. */
export function defaultMigrationsFolder(): string {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../drizzle");
}

export async function runMigrations(db: DpDb, migrationsFolder = defaultMigrationsFolder()): Promise<void> {
  await migrate(db, { migrationsFolder, migrationsTable: "__dp_migrations" });
}
